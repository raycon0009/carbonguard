// Deploys CarbonGuard and the example CarbonMarket, and writes web/deployment.js
// so the dashboard can find them.
const fs = require("fs");
const path = require("path");
const hre = require("hardhat");

const NETWORKS = {
  31337: { name: "Hardhat local", rpc: "http://127.0.0.1:8545", explorer: "" },
};

async function main() {
  const [deployer] = await hre.ethers.getSigners();
  const { chainId } = await hre.ethers.provider.getNetwork();
  console.log(`Deploying from ${deployer.address} on chain ${chainId}`);

  const cg = await hre.ethers.deployContract("CarbonGuard", [deployer.address]);
  await cg.waitForDeployment();
  const address = await cg.getAddress();
  const deployBlock = (await cg.deploymentTransaction().wait()).blockNumber;
  console.log(`CarbonGuard deployed at ${address} (block ${deployBlock})`);

  const market = await hre.ethers.deployContract("CarbonMarket", [address]);
  await market.waitForDeployment();
  const marketAddress = await market.getAddress();
  console.log(`CarbonMarket deployed at ${marketAddress}`);

  const { abi } = await hre.artifacts.readArtifact("CarbonGuard");
  const config = {
    address,
    chainId: Number(chainId),
    deployBlock,
    admin: deployer.address,
    ...(NETWORKS[Number(chainId)] || { name: `chain ${chainId}`, rpc: "", explorer: "" }),
    abi,
    market: { address: marketAddress, abi: (await hre.artifacts.readArtifact("CarbonMarket")).abi },
  };
  const out = path.join(__dirname, "..", "web", "deployment.js");
  fs.writeFileSync(out, `// Generated by scripts/deploy.js\nwindow.CG_CONFIG = ${JSON.stringify(config, null, 1)};\n`);
  console.log(`Wrote ${out}`);
}

main().catch((e) => {
  console.error(e);
  process.exitCode = 1;
});
