// The AI -> blockchain bridge (oracle).
// Reads the model output from ai/ and, for a curated set of demo projects:
//   1. bridges one vintage batch per project (registry serial range -> tokens)
//   2. writes the AI risk score, top reasons, model hash and data hash on chain.
// In production this runs as a Chainlink Functions job or a signed oracle service.
const fs = require("fs");
const path = require("path");
const hre = require("hardhat");

const AI = path.join(__dirname, "..", "ai");
const DEMO_SIZE = { Low: 9, Medium: 5, High: 7 };

function pickDemoProjects(projects) {
  const picked = [];
  for (const [tier, n] of Object.entries(DEMO_SIZE)) {
    const pool = projects
      .filter((p) => p.risk_tier === tier)
      // diverse project types first, then by score so the demo shows clear cases
      .sort((a, b) => (tier === "Low" ? a.risk_score - b.risk_score : b.risk_score - a.risk_score));
    const seenTypes = new Set();
    for (const p of pool) {
      if (picked.filter((x) => x.risk_tier === tier).length >= n) break;
      if (seenTypes.has(p.project_type)) continue;
      seenTypes.add(p.project_type);
      picked.push(p);
    }
    for (const p of pool) {
      if (picked.filter((x) => x.risk_tier === tier).length >= n) break;
      if (!picked.includes(p)) picked.push(p);
    }
  }
  return picked;
}

async function main() {
  const projects = JSON.parse(fs.readFileSync(path.join(AI, "data", "projects_scored.json"), "utf8"));
  const meta = JSON.parse(fs.readFileSync(path.join(AI, "model", "model_meta.json"), "utf8"));
  const { address } = loadDeployment();
  const [signer] = await hre.ethers.getSigners();
  const cg = await hre.ethers.getContractAt("CarbonGuard", address, signer);

  // Publish model card for the dashboard (provenance: same hashes as on chain)
  fs.writeFileSync(
    path.join(__dirname, "..", "web", "model.js"),
    `// Generated by scripts/oracle_push_scores.js
window.CG_MODEL = ${JSON.stringify(meta, null, 1)};
`
  );

  writeBatchInputs(projects);

  console.log(`Model ${meta.model_version}  model=${meta.model_hash.slice(0, 18)}…  data=${meta.data_hash.slice(0, 18)}…`);
  for (const r of await pushScores(cg, signer, projects, meta)) {
    console.log(
      `#${r.tokenId}  ${r.project.project_id.padEnd(8)} ${r.project.project_type.padEnd(30)} ${String(r.amount).padStart(9)} t  risk ${String(r.project.risk_score).padStart(3)} ${r.project.risk_tier}`
    );
  }
}

// The projects bridged in the demo, in order.
function demoProjects(projects) {
  const demo = pickDemoProjects(projects);
  // Guarantee one clean project with an Article 6 corresponding adjustment for the compliance demo.
  const caLow = projects.find((p) => p.risk_tier === "Low" && p.has_corresponding_adjustment);
  if (caLow && !demo.includes(caLow)) demo[0] = caLow;
  return demo;
}

// The registry inputs behind every demo score, so the dashboard can re-run the
// model in the browser (web/scorer.js) and compare with what is on chain.
// Synthetic batches carry their out-of-fold score: cross-validation scored each
// one with a model that never saw it, so the final model can differ slightly.
// Real projects carry one input version per score the oracle writes for them.
const RAW_FIELDS = ["project_type", "first_vintage", "last_vintage", "est_annual_reductions", "total_issued",
  "total_retired", "max_to_median_issuance", "buffer_pool_pct", "satellite_cover_delta_pct", "verifier_changes"];
const pickRaw = (p) => Object.fromEntries(RAW_FIELDS.map((k) => [k, p[k] ?? null]));

// Minimal RFC 4180 parser (quoted fields, doubled quotes).
function parseCsv(text) {
  const rows = [];
  let row = [], field = "", quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") { row.push(field); field = ""; }
    else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++;
      row.push(field); rows.push(row); row = []; field = "";
    } else field += c;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  const [header, ...body] = rows;
  return body.filter((r) => r.length === header.length).map((r) => Object.fromEntries(header.map((h, i) => [h, r[i]])));
}

function batchInputs(projects) {
  const meta = JSON.parse(fs.readFileSync(path.join(AI, "model", "model_meta.json"), "utf8"));
  const batches = {};
  for (const p of demoProjects(projects)) {
    batches[p.project_id] = {
      source: "synthetic",
      out_of_fold_score: p.risk_score,
      versions: [{ label: "Registry data", raw: pickRaw(p) }],
    };
  }
  const summary = JSON.parse(fs.readFileSync(path.join(AI, "real_world", "summary.json"), "utf8"));
  const real = new Map(parseCsv(fs.readFileSync(path.join(AI, "data", "real_projects.csv"), "utf8")).map((r) => [r.project_id, r]));
  for (const s of summary.satellite.filter((x) => x.measurable)) {
    const row = real.get(s.project_id);
    if (!row) continue;
    const raw = pickRaw(Object.fromEntries(RAW_FIELDS.map((k) => [k, k === "project_type" ? row[k] : row[k] === "" ? null : Number(row[k])])));
    batches[s.project_id] = {
      source: "real",
      name: s.name,
      versions: [
        { label: "Registry data only", raw: { ...raw, satellite_cover_delta_pct: null } },
        { label: "Registry data + yearly satellite measurement", raw: { ...raw, satellite_cover_delta_pct: -100 * s.gap } },
      ],
    };
  }
  return { model_hash: meta.model_hash, batches };
}

function writeBatchInputs(projects) {
  fs.writeFileSync(
    path.join(__dirname, "..", "web", "batch_inputs.js"),
    `// Generated by scripts/oracle_push_scores.js - do not edit
window.CG_BATCH_INPUTS = ${JSON.stringify(batchInputs(projects), null, 1)};
`
  );
}

// Bridge the demo projects and write their AI scores on chain. Returns one
// record per batch so callers (and tests) can check what was written.
async function pushScores(cg, signer, projects, meta) {
  const demo = demoProjects(projects);

  const results = [];
  for (const p of demo) {
    const years = p.last_vintage - p.first_vintage + 1;
    const amount = BigInt(Math.max(1000, Math.round(p.total_issued / years)));
    // Deterministic pseudo-registry serial block, unique per project.
    const serialFrom = BigInt(p.project_id.replace(/\D/g, "")) * 10n ** 9n + 1n;
    const input = {
      registry: p.registry,
      projectId: p.project_id,
      projectType: p.project_type,
      country: p.country,
      vintage: p.last_vintage,
      serialFrom,
      serialTo: serialFrom + amount - 1n,
      correspondingAdjustment: Boolean(p.has_corresponding_adjustment),
    };
    const tx = await cg.connect(signer).registerBatch(input, signer.address);
    const rcpt = await tx.wait();
    const ev = rcpt.logs.map((l) => cg.interface.parseLog(l)).find((e) => e && e.name === "BatchRegistered");
    const tokenId = ev.args.tokenId;

    const scoreTx = await cg.connect(signer).setRiskScore(tokenId, p.risk_score, p.reasons, meta.model_hash, meta.data_hash);
    const scoreRcpt = await scoreTx.wait();
    results.push({ tokenId, project: p, amount, scoreGas: scoreRcpt.gasUsed });
  }
  return results;
}

// The local deployment written by scripts/deploy.js.
function loadDeployment() {
  const src = fs.readFileSync(path.join(__dirname, "..", "web", "deployment.js"), "utf8");
  return JSON.parse(src.slice(src.indexOf("{"), src.lastIndexOf("}") + 1));
}

module.exports = { loadDeployment, pickDemoProjects, pushScores, batchInputs };

if (require.main === module && process.argv.includes("--inputs-only")) {
  // Regenerate web/batch_inputs.js without a chain:  npm run export:inputs
  writeBatchInputs(JSON.parse(fs.readFileSync(path.join(AI, "data", "projects_scored.json"), "utf8")));
  console.log("Wrote web/batch_inputs.js");
} else if (require.main === module) {
  main().catch((e) => {
    console.error(e);
    process.exitCode = 1;
  });
}
