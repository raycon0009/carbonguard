// Measures the real gas used by every CarbonGuard action and turns it into an
// approximate cost per network. Gas is measured on the in-process Hardhat chain;
// prices are ASSUMPTIONS stated below - edit them before quoting numbers.
//   npx hardhat run scripts/gas_report.js
const fs = require("fs");
const path = require("path");
const hre = require("hardhat");

const ASSUMPTIONS = {
  ethUsd: 3000, // assumed ETH price in USD
  networks: {
    "Ethereum mainnet": { gwei: 2, note: "assumed typical base + priority fee" },
    "Base (L2)": { gwei: 0.01, note: "L2 execution only; excludes the L1 data fee" },
  },
};

async function measureGas() {
  const { ethers } = hre;
  const [admin, oracle, developer, buyer, v1] = await ethers.getSigners();
  const cg = await ethers.deployContract("CarbonGuard", [admin.address]);
  const deployGas = (await cg.deploymentTransaction().wait()).gasUsed;
  await (await cg.grantRole(await cg.ORACLE_ROLE(), oracle.address)).wait();

  const projects = JSON.parse(fs.readFileSync(path.join(__dirname, "..", "ai", "data", "projects_scored.json"), "utf8"));
  const longestReasons = projects.map((p) => p.reasons).reduce((a, b) => (b.length > a.length ? b : a));
  const MODEL = ethers.id("model");
  const DATA = ethers.id("data");
  const batch = (id, ca) => ({
    registry: "VCS", projectId: `VCS${id}`, projectType: "REDD+", country: "Peru", vintage: 2021,
    serialFrom: 1n, serialTo: 1_000_000n, correspondingAdjustment: ca,
  });
  const gas = async (tx) => (await (await tx).wait()).gasUsed;

  const rows = [];
  rows.push(["Deploy contract (one-off)", deployGas]);
  rows.push(["Bridge a registry batch (registerBatch)", await gas(cg.registerBatch(batch(1, true), developer.address))]);
  rows.push(["Write AI score + reasons + hashes (longest real explanation)",
    await gas(cg.connect(oracle).setRiskScore(1, 22, longestReasons, MODEL, DATA))]);
  rows.push(["Transfer credits to a buyer", await gas(cg.connect(developer).safeTransferFrom(developer.address, buyer.address, 1, 1000, "0x"))]);
  rows.push(["Retire credits (voluntary claim, with certificate)", await gas(cg.connect(buyer).retire(1, 500, "Acme Corp", "FY2025 Scope 1 offset", false))]);
  rows.push(["Retire credits (Article 6 compliance claim)", await gas(cg.connect(buyer).retire(1, 500, "Acme Corp", "CORSIA 2025", true))]);

  await (await cg.registerBatch(batch(2, false), developer.address)).wait();
  await (await cg.connect(oracle).setRiskScore(2, 92, "Issuance spike", MODEL, DATA)).wait();
  await (await cg.grantRole(await cg.VERIFIER_ROLE(), v1.address)).wait();
  await (await cg.setRequiredApprovals(2)).wait();
  rows.push(["Verifier vote (1 of 2)", await gas(cg.verifierDecision(2, true, "Field audit OK"))]);
  rows.push(["Verifier vote that unfreezes (2 of 2)", await gas(cg.connect(v1).verifierDecision(2, true, "Satellite re-check OK"))]);

  // Example marketplace
  const market = await ethers.deployContract("CarbonMarket", [await cg.getAddress()]);
  await (await cg.connect(developer).setApprovalForAll(await market.getAddress(), true)).wait();
  const price = ethers.parseEther("0.001");
  rows.push(["Marketplace: list credits for sale", await gas(market.connect(developer).list(1, 10_000, price))]);
  rows.push(["Marketplace: buy credits", await gas(market.connect(buyer).buy(0, 100, { value: 100n * price }))]);
  return rows.map(([action, g]) => ({ action, gas: Number(g) }));
}

const usd = (gas, gwei) => (gas * gwei * 1e-9 * ASSUMPTIONS.ethUsd);
const fmtUsd = (x) => (x < 0.01 ? `$${x.toFixed(4)}` : `$${x.toFixed(2)}`);

async function main() {
  const rows = await measureGas();
  const nets = Object.entries(ASSUMPTIONS.networks);
  const lines = [
    "# What CarbonGuard costs to run",
    "",
    "Gas is **measured** by `scripts/gas_report.js` against the real contract. Dollar figures are **estimates** that",
    `assume ETH = $${ASSUMPTIONS.ethUsd} and ${nets.map(([n, a]) => `${a.gwei} gwei on ${n} (${a.note})`).join("; ")}.`,
    "Rerun with current prices before quoting them.",
    "",
    `| Action | Gas | ${nets.map(([n]) => n).join(" | ")} |`,
    `|---|---:|${nets.map(() => "---:").join("|")}|`,
    ...rows.map((r) => `| ${r.action} | ${r.gas.toLocaleString("en-US")} | ${nets.map(([, a]) => fmtUsd(usd(r.gas, a.gwei))).join(" | ")} |`),
    "",
    "A retirement costs the same whether it covers 1 tonne or 1 million tonnes.",
    "",
  ];
  fs.writeFileSync(path.join(__dirname, "..", "docs", "costs.md"), lines.join("\n"));
  const retire = rows.find((r) => r.action.startsWith("Retire credits (voluntary")).gas;
  const web = {
    ethUsd: ASSUMPTIONS.ethUsd,
    retireGas: retire,
    perNetwork: Object.fromEntries(nets.map(([n, a]) => [n, { gwei: a.gwei, retireUsd: usd(retire, a.gwei), note: a.note }])),
    rows,
  };
  fs.writeFileSync(path.join(__dirname, "..", "web", "costs.js"),
    `// Generated by scripts/gas_report.js\nwindow.CG_COSTS = ${JSON.stringify(web, null, 1)};\n`);
  console.log(lines.join("\n"));
}

module.exports = { measureGas, ASSUMPTIONS };

if (require.main === module) {
  main().catch((e) => {
    console.error(e);
    process.exitCode = 1;
  });
}
